import { createRequire } from "node:module";
import { mkdtemp, mkdir, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve, join, dirname } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(join(root, "packages/client/package.json"));
const { build } = await import(pathToFileURL(join(dirname(require.resolve("vite/package.json")), "dist/node/index.js")).href);
const temporary = await mkdtemp(join(tmpdir(), "be-district-icons-"));
try {
  await build({ configFile: false, logLevel: "warn", build: {
    outDir: temporary, emptyOutDir: false,
    lib: { entry: resolve(root, "packages/client/src/client-town-district/district-icon-svg.ts"), formats: ["es"], fileName: () => "icons.mjs" }
  } });
  const { districtIconSvg, districtIconKinds } = await import(pathToFileURL(join(temporary, "icons.mjs")).href);
  const destination = join(root, "packages/client/public/overlays/town-district");
  await mkdir(destination, { recursive: true });
  const cropRows = [];
  for (const kind of districtIconKinds()) {
    const svg = districtIconSvg(kind);
    await writeFile(join(destination, `${kind.toLowerCase().replaceAll("_", "-")}.svg`), svg);
    const points = [...svg.matchAll(/ d="([^"]+)"/g)].flatMap(match => {
      const values = match[1].match(/-?\d+(?:\.\d+)?/g).map(Number);
      return Array.from({ length: values.length / 2 }, (_, i) => [values[i * 2], values[i * 2 + 1]]);
    });
    if (!points.length) throw new Error(`No visible icon geometry for ${kind}`);
    // Exact path bounds with a one-pixel antialias margin on the 128px SVG.
    const minX = Math.max(0, Math.min(...points.map(p => p[0])) - 1);
    const minY = Math.max(0, Math.min(...points.map(p => p[1])) - 1);
    const maxX = Math.min(128, Math.max(...points.map(p => p[0])) + 1);
    const maxY = Math.min(128, Math.max(...points.map(p => p[1])) + 1);
    const crop = [minX, minY, maxX - minX, maxY - minY].map(value => +(value / 128).toFixed(6));
    cropRows.push(`  ${kind}: [${crop.join(", ")}],`);
  }
  await writeFile(join(root, "packages/client/src/client-town-district/district-icon-crops.ts"),
    'import type { DistrictBuildingKind } from "./district-catalog.js";\n\n' +
    '// Generated by scripts/generate-town-district-icons.mjs from SVG path bounds.\n' +
    'export type DistrictIconCrop = readonly [x: number, y: number, width: number, height: number];\n' +
    'export const DISTRICT_ICON_CROPS: Readonly<Record<DistrictBuildingKind, DistrictIconCrop>> = {\n' + cropRows.join("\n") + '\n};\n');
  console.log(`Generated ${districtIconKinds().length} district icons from the production models.`);
} finally { await rm(temporary, { recursive: true, force: true }); }
