import { createRequire } from "node:module";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve, join, dirname } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(join(root, "packages/client/package.json"));
const { build } = await import(pathToFileURL(join(dirname(require.resolve("vite/package.json")), "dist/node/index.js")).href);
const temporary = await mkdtemp(join(tmpdir(), "be-district-icons-"));
try {
  await build({ configFile: false, logLevel: "warn", build: {
    outDir: temporary, emptyOutDir: false,
    lib: { entry: resolve(root, "packages/client/src/client-structure-info-catalog/structure-review-svg.ts"), formats: ["es"], fileName: () => "icons.mjs" }
  } });
  const { structureReviewSvg, structureReviewInfrastructureExports } = await import(pathToFileURL(join(temporary, "icons.mjs")).href);
  const crops = [];
  for (const { kind, resource, filename } of structureReviewInfrastructureExports) {
    const svg = structureReviewSvg(kind, resource);
    await writeFile(join(root, "packages/client/public/overlays", filename), svg);
    const points = [...svg.matchAll(/ d="([^"]+)"/g)].flatMap(match => {
      const values = match[1].match(/-?\d+(?:\.\d+)?/g).map(Number);
      return Array.from({length: values.length / 2}, (_, i) => [values[i * 2], values[i * 2 + 1]]);
    });
    const minX = Math.max(0, Math.min(...points.map(p => p[0])) - 1);
    const minY = Math.max(0, Math.min(...points.map(p => p[1])) - 1);
    const maxX = Math.min(128, Math.max(...points.map(p => p[0])) + 1);
    const maxY = Math.min(128, Math.max(...points.map(p => p[1])) + 1);
    crops.push(`  "/overlays/${filename}": [${[minX, minY, maxX-minX, maxY-minY].map(v => +(v/128).toFixed(6)).join(", ")}],`);
  }
  await writeFile(join(root, "packages/client/src/client-infrastructure/infrastructure-icon-crops.ts"),
    '// Generated by scripts/generate-infrastructure-icons.mjs from production mesh projections.\n' +
    'export const INFRASTRUCTURE_ICON_CROPS: Readonly<Record<string, readonly [number, number, number, number]>> = {\n' + crops.join("\n") + '\n};\n');
  console.log(`Generated ${structureReviewInfrastructureExports.length} infrastructure icons and exact menu crops.`);
} finally { await rm(temporary, { recursive: true, force: true }); }
